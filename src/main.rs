use std::{env,fs,path::{Path,PathBuf},process::Command};
fn entry(path:&Path)->Result<(PathBuf,Option<PathBuf>),String>{
 if path.is_file(){return Ok((path.to_path_buf(),None));}
 if !path.is_dir(){return Err(format!("source does not exist: {}",path.display()));}
 for name in ["index.php","main.php","index.phx","main.phx"] {let p=path.join(name);if p.is_file(){return Ok((p,Some(path.to_path_buf())));}}
 Ok((path.join("index.php"),Some(path.to_path_buf())))
}
const PHIX_VERSION: &str = env!("CARGO_PKG_VERSION");
fn run()->Result<(),String>{
 let args:Vec<String>=env::args().collect();
 if args.len()==2 && (args[1]=="--version" || args[1]=="-V" || args[1]=="version") { println!("Phix v{PHIX_VERSION}"); return Ok(()); }
 if args.len()<3 || !(args[1]=="build"||args[1]=="check") {return Err("usage: phix build|check PROJECT [-o OUTPUT] [--emit-rs FILE]".into());}
 let source=Path::new(&args[2]);
 let (default_entry,project)=entry(source)?;
 let build_cfg=build_config::BuildConfig::load(project.as_deref())?;
 let mut entry=build_cfg.entrypoint(project.as_deref(),default_entry)?;
 // Framework projects commonly have public/index.php without a root index.php.
 if !entry.is_file(){
  if let Some(root)=project.as_deref(){
   for candidate in ["index.php","main.php","index.phx","main.phx"] {
    let path=root.join(&build_cfg.routing.document_root).join(candidate);
    if path.is_file(){entry=path;break;}
   }
  }
 }
 if !entry.is_file(){return Err(format!("no entrypoint found in {} (index.php, main.php, index.phx, main.phx, or phix.json entry)",source.display()));}
 let mut output=PathBuf::from("app");let mut emit=None;
 let mut i=3;while i<args.len(){match args[i].as_str(){"-o"|"--emit-rs" if i+1<args.len()=>{if args[i]=="-o"{output=PathBuf::from(&args[i+1]);}else{emit=Some(PathBuf::from(&args[i+1]));}i+=2;},x=>return Err(format!("unknown option: {x}"))}}
 build_cfg.storage.validate(project.as_deref())?;
 let tokens=modules::expand(&entry)?;
 let _validated_entry=compiler::compile(&tokens).map_err(|error| diagnostics::render(&error,&tokens,&entry))?;
 if args[1]=="check" {println!("Phix check passed: {}",entry.display());return Ok(());}
 let mut code=format!("// Generated by Phix v{PHIX_VERSION}: pure Rust, no C runtime.\nconst PHIX_VERSION: &str = {:?};\n", PHIX_VERSION);
 code.push_str(include_str!("../runtime/php_array.rs"));code.push('\n');code.push_str(include_str!("../runtime/json.rs"));code.push('\n');code.push_str(include_str!("../runtime/php_reference.rs"));code.push('\n');code.push_str(include_str!("../runtime/php_reference_cell.rs"));code.push('\n');code.push_str(include_str!("../runtime/web_runtime.rs"));code.push('\n');code.push_str(&routing::generate(project.as_deref(),&build_cfg.routing,&build_cfg.storage,&entry)?);code.push_str(&build_cfg.storage.emitted());code.push_str(&assets::emit(project.as_deref(),build_cfg.storage.uploads.as_deref())?);
 code.push_str("fn main() { if std::env::args().any(|a| a == \"--version\" || a == \"-V\") { println!(\"Phix v{}\", PHIX_VERSION); return; } if let Err(err) = phix_serve() { eprintln!(\"phix: {err}\"); std::process::exit(1); } }\n");
 let keep=emit.is_some();
 let rsfile=emit.unwrap_or_else(||env::temp_dir().join(format!("phix-rust-{}-{}.rs",std::process::id(),std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos())));
 fs::write(&rsfile,code).map_err(|e|e.to_string())?;
 let result=Command::new(env::var("RUSTC").unwrap_or_else(|_|"rustc".into())).arg("--edition=2021").arg("--crate-name").arg("phix_generated").arg("-O").arg("-A").arg("warnings").arg(&rsfile).arg("-o").arg(&output).status().map_err(|e|format!("cannot launch rustc: {e}"));
 if !keep{let _=fs::remove_file(&rsfile);}
 if !result?.success(){return Err("generated Rust compilation failed".into());}
 let config_action=build_config::deploy_config(project.as_deref(),&output)?;
 println!("Built {}",output.display());
 println!("Runtime config: {config_action}");
 let storage_action=build_cfg.storage.deploy(project.as_deref(),&output)?;println!("Runtime storage: {storage_action}");Ok(())
}
fn main(){if let Err(e)=run(){eprintln!("phix: {e}");std::process::exit(1)}}
